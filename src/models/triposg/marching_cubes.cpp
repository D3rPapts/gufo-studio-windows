struct EdgeKey {
    std::uint64_t v;
    bool operator==(const EdgeKey& o) const { return v == o.v; }
};
struct EdgeKeyHash {
    std::size_t operator()(const EdgeKey& k) const {
        std::uint64_t x = k.v;
        x ^= x >> 33; x *= 0xff51afd7ed558ccdULL; x ^= x >> 33;
        x *= 0xc4ceb9fe1a85ec53ULL; x ^= x >> 33;
        return static_cast<std::size_t>(x);
    }
};

// Unique key for a grid edge: the lower corner (ix, iy, iz) plus the axis (0..2).
inline EdgeKey make_edge_key(std::size_t ix, std::size_t iy, std::size_t iz, int axis) {
    return EdgeKey{(static_cast<std::uint64_t>(ix) << 42) | (static_cast<std::uint64_t>(iy) << 22) |
                   (static_cast<std::uint64_t>(iz) << 2) | static_cast<std::uint64_t>(axis)};
}

