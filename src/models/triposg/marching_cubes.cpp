Mesh marching_cubes(const ScalarGrid& grid, const MarchingCubesOptions& options) {
    Mesh mesh;
    if ((grid.values == nullptr && grid.half_values == nullptr) || grid.nx < 2 || grid.ny < 2 || grid.nz < 2) return mesh;

    const float iso = options.iso_level;
    // Bourke's table assumes bit i set when corner i is "inside" (value below iso).
    // A field that is positive inside is equivalent to a negated plain SDF.
    const float sign = options.inside_positive ? -1.f : 1.f;

    float step[3];
    const std::size_t n[3] = {grid.nx, grid.ny, grid.nz};
    for (int a = 0; a < 3; ++a) step[a] = (grid.max[a] - grid.min[a]) / static_cast<float>(n[a] - 1);

    std::unordered_map<EdgeKey, std::uint32_t, EdgeKeyHash> edge_vertex;
    if (options.weld) edge_vertex.reserve(grid.nx * grid.ny * 4);

    auto emit_vertex = [&](std::size_t ix, std::size_t iy, std::size_t iz, int edge,
                           const float corner_val[8]) -> std::uint32_t {
        const int c0 = kEdgeCorners[edge][0];
        const int c1 = kEdgeCorners[edge][1];
        // Lower corner of the edge and its axis for the weld key.
        int axis = 0;
        for (int a = 0; a < 3; ++a)
            if (kCornerOffset[c0][a] != kCornerOffset[c1][a]) axis = a;
        const int lo = (kCornerOffset[c0][axis] < kCornerOffset[c1][axis]) ? c0 : c1;
        const std::size_t kx = ix + static_cast<std::size_t>(kCornerOffset[lo][0]);
        const std::size_t ky = iy + static_cast<std::size_t>(kCornerOffset[lo][1]);
        const std::size_t kz = iz + static_cast<std::size_t>(kCornerOffset[lo][2]);
        if (options.weld) {
            auto it = edge_vertex.find(make_edge_key(kx, ky, kz, axis));
            if (it != edge_vertex.end()) return it->second;
        }
        const float v0 = corner_val[c0];
        const float v1 = corner_val[c1];
        float t = 0.5f;
        const float d = v1 - v0;
        if (std::fabs(d) > 1e-12f) t = (iso - v0) / d;
        t = std::min(1.f, std::max(0.f, t));
        float p[3];
        for (int a = 0; a < 3; ++a) {
            const float g0 = static_cast<float>(kCornerOffset[c0][a]);
            const float g1 = static_cast<float>(kCornerOffset[c1][a]);
            const float base = static_cast<float>((a == 0) ? ix : (a == 1) ? iy : iz);
            p[a] = grid.min[a] + (base + g0 + (g1 - g0) * t) * step[a];
        }
        const auto index = static_cast<std::uint32_t>(mesh.vertices.size());
        mesh.vertices.push_back(MeshVertex{p[0], p[1], p[2]});
        if (options.weld) edge_vertex.emplace(make_edge_key(kx, ky, kz, axis), index);
        return index;
    };

    for (std::size_t ix = 0; ix + 1 < grid.nx; ++ix) {
        for (std::size_t iy = 0; iy + 1 < grid.ny; ++iy) {
            for (std::size_t iz = 0; iz + 1 < grid.nz; ++iz) {
                float corner_val[8];
                int cube_index = 0;
                for (int c = 0; c < 8; ++c) {
                    corner_val[c] = sign * grid.at(ix + static_cast<std::size_t>(kCornerOffset[c][0]),
                                                   iy + static_cast<std::size_t>(kCornerOffset[c][1]),
                                                   iz + static_cast<std::size_t>(kCornerOffset[c][2]));
                    if (corner_val[c] < iso) cube_index |= (1 << c);
                }
                if (cube_index == 0 || cube_index == 255) continue;
                const signed char* tri = kTriTable[cube_index];
                for (int i = 0; tri[i] != -1; i += 3) {
                    const std::uint32_t a = emit_vertex(ix, iy, iz, tri[i], corner_val);
                    const std::uint32_t b = emit_vertex(ix, iy, iz, tri[i + 1], corner_val);
                    const std::uint32_t c = emit_vertex(ix, iy, iz, tri[i + 2], corner_val);
                    if (a == b || b == c || a == c) continue;  // degenerate (t clamped onto a corner)
                    // The table winds clockwise seen from outside for "inside = below iso";
                    // swap to counter-clockwise (outward normals, positive signed volume).
                    mesh.faces.push_back({a, c, b});
                }
            }
        }
    }
    return mesh;
}

std::size_t count_open_edges(const Mesh& mesh) {
    // Each directed edge (a->b) must occur once and be matched by exactly one (b->a).
    std::unordered_map<std::uint64_t, int> directed;
    directed.reserve(mesh.faces.size() * 3);
    for (const auto& f : mesh.faces) {
        for (int k = 0; k < 3; ++k) {
            const std::uint64_t a = f[static_cast<std::size_t>(k)];
            const std::uint64_t b = f[static_cast<std::size_t>((k + 1) % 3)];
            directed[(a << 32) | b] += 1;
        }
    }
    std::size_t bad = 0;
    for (const auto& [key, count] : directed) {
        const std::uint64_t rev = (key << 32) | (key >> 32);
        auto it = directed.find(rev);
        if (count != 1 || it == directed.end() || it->second != 1) ++bad;
    }
    return bad;
}

double signed_volume(const Mesh& mesh) {
    double vol = 0.0;
    for (const auto& f : mesh.faces) {
        const MeshVertex& a = mesh.vertices[f[0]];
        const MeshVertex& b = mesh.vertices[f[1]];
        const MeshVertex& c = mesh.vertices[f[2]];
        const double cx = static_cast<double>(b.y) * c.z - static_cast<double>(b.z) * c.y;
        const double cy = static_cast<double>(b.z) * c.x - static_cast<double>(b.x) * c.z;
        const double cz = static_cast<double>(b.x) * c.y - static_cast<double>(b.y) * c.x;
        vol += a.x * cx + a.y * cy + a.z * cz;
    }
    return vol / 6.0;
}

bool bounding_box(const Mesh& mesh, float out_min[3], float out_max[3]) {
    if (mesh.vertices.empty()) return false;
    out_min[0] = out_max[0] = mesh.vertices[0].x;
    out_min[1] = out_max[1] = mesh.vertices[0].y;
    out_min[2] = out_max[2] = mesh.vertices[0].z;
    for (const auto& v : mesh.vertices) {
        out_min[0] = std::min(out_min[0], v.x); out_max[0] = std::max(out_max[0], v.x);
        out_min[1] = std::min(out_min[1], v.y); out_max[1] = std::max(out_max[1], v.y);
        out_min[2] = std::min(out_min[2], v.z); out_max[2] = std::max(out_max[2], v.z);
    }
    return true;
}

